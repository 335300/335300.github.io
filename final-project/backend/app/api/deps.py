"""Shared dependencies: the data store, bearer-token auth, path helpers."""

from __future__ import annotations

import hmac
import os
from datetime import date

from fastapi import Depends, Header, HTTPException, status

from ..config import DEFAULT_PROFILE, JOINT_PROFILE
from ..models import YearData
from ..storage import AppStore, Repository

_store: AppStore | None = None


def set_store(store: AppStore) -> None:
    global _store
    _store = store


def get_store() -> AppStore:
    if _store is None:  # pragma: no cover - startup always sets it
        raise RuntimeError("Store not configured")
    return _store


def get_repository(store: AppStore = Depends(get_store)) -> Repository:
    """The repository of whichever profile is open."""
    return store.repo()


def get_today() -> date:
    """The clock lives here, at the edge — services receive ``today`` as input.

    Tests override this dependency to pin the date.
    """
    return date.today()


def sync_joint_links(store: AppStore, today: date) -> None:
    """Bring the two Joint links up to date, whichever profile is open:
    each person's planned contribution in Joint, and the owner's part of the
    Joint plan as the "Transfer to Joint" budget in Personal."""
    from ..services import joint

    personal, shared = store.repo(DEFAULT_PROFILE), store.repo(JOINT_PROFILE)
    with personal.lock, shared.lock:
        if joint.sync_contributions(shared.data, today):
            shared.save()
        if joint.sync_personal_half(personal.data, shared.data, today):
            personal.save()


def get_synced_repository(store: AppStore = Depends(get_store), today: date = Depends(get_today)) -> Repository:
    """The open profile's repository, after :func:`sync_joint_links` — for the
    reads that show plans or forecasts."""
    sync_joint_links(store, today)
    return store.repo()


def require_token(authorization: str | None = Header(default=None)) -> None:
    """Reject anything that is not the Electron shell we were launched by.

    The server binds to loopback only, but any local process (including a web
    page in a browser) can reach loopback. The one-shot token generated by
    ``main.js`` at spawn time is what makes this a private backend.
    """
    expected = os.environ.get("CENTWISE_TOKEN")
    if not expected:
        return  # No token configured (tests, local dev) — auth disabled.
    supplied = ""
    if authorization and authorization.lower().startswith("bearer "):
        supplied = authorization[7:]
    if not hmac.compare_digest(supplied, expected):
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid or missing token")


def get_year(year: int, repo: Repository = Depends(get_repository)) -> YearData:
    """Resolve a ``{year}`` path parameter, 404-ing when it does not exist."""
    try:
        return repo.year(year)
    except KeyError:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail=f"Year {year} is not tracked yet"
        ) from None


def not_found(detail: str) -> HTTPException:
    return HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=detail)


def conflict(detail: str) -> HTTPException:
    return HTTPException(status_code=status.HTTP_409_CONFLICT, detail=detail)


def bad_request(detail: str) -> HTTPException:
    return HTTPException(status_code=422, detail=detail)
